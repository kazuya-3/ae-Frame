/**
 * お礼（チップ）の設定。
 *
 * ── 建てつけ ──
 *
 * Stripe がチップに求めるのは「**すでに提供した商品・サービス**に対する
 * 任意の支払い」であること。将来の成果物に触れた瞬間、それは資金調達になり、
 * 一度そこで止められている（docs/stripe-compliance.md）。
 *
 * また Stripe は「寄付」を別物として扱う。寄付には**果たすと約束した
 * 慈善の目的**が要る。この道具にそれは無いので、寄付とは呼ばない。
 * 呼ぶのは「もう使ってもらったこと自体へのお礼」。
 *
 * ── 見返りを1つも作らない ──
 *
 * 特定商取引法の表示義務（氏名・住所・電話番号）がかかるのは、
 * 対価を取って物や役務を売るとき。**渡すものが1つも無ければ売っていない**、
 * というのがこちらの整理。だから「払うと増える機能」を作らない。
 * 作った瞬間に、住所と電話番号を公開する話になる。
 *
 * これは設計の都合ではなく、**この機能の中身そのもの**。
 * 検証でも「入口の有無で、つくる画面が1つも変わらないこと」を見ている。
 *
 * ── 既定は空 ──
 *
 * リンクを入れるのは、Stripe に事前確認を取って「可」の返事をもらったあと。
 * 空のあいだは、入口も文言も**配るものに入らない**（vite.config.ts）。
 * 前回は条件分岐の向こうに置いただけで、文字列は配られる JS に残っていた。
 */

/** 送り先。ビルドのときに VITE_TIP_URL から入る。空なら機能ごと無い */
const RAW = import.meta.env.VITE_TIP_URL ?? '';

/**
 * 送り先として使ってよい形か。
 *
 * http で始まらないもの、javascript: のようなものを、そのまま
 * 新しいタブで開かせない。設定ミスが、そのまま穴になる場所なので。
 */
function usable(url: string): boolean {
  if (!url) return false;
  try {
    return new URL(url).protocol === 'https:';
  } catch {
    return false;
  }
}

export const TIP_URL = usable(RAW) ? RAW : '';

/** お礼の入口を出すか。ビルドのときに決まる */
export const TIP_ON = TIP_URL !== '';
